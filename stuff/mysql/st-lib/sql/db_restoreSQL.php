function Check_Upload()
{
	global $_POST, $_FILES, $ErrorMSG, $StoragePath, $Type, $FileName;

	if($_POST['existing_file']=="dummy")
	{
		if($_FILES['SQLDumpFile']['name'] == "" || $_FILES['SQLDumpFile']['name'] == "none")
		{
			$ErrorMSG = "&#149;&nbsp;Please upload an SQL file\n";
			return;
		}

		if(isset($_FILES['SQLDumpFile']['size']) && $_FILES['SQLDumpFile']['size'] > 10485760)
		{
			$ErrorMSG = "&#149;&nbsp;Filesize too big! max. 10 MB\n";
			return;
		}

		if(isset($_FILES['SQLDumpFile']['size']) && $_FILES['SQLDumpFile']['size'] < 1)
		{
			$ErrorMSG = "&#149;&nbsp;File missing or size is zero\n";
			return;
		}

		if(!stristr(basename($_FILES['SQLDumpFile']['name']), ".sql") && !stristr(basename($_FILES['SQLDumpFile']['name']), ".gz"))
		{
			$ErrorMSG = "&#149;&nbsp;Sorry, you can only upload uncompressed or GZipped SQL-files\n";
			return;
		}

		if (stristr(basename($_FILES['SQLDumpFile']['name']), ".gz"))
		{
			$Type = "gzip";

			if (!move_uploaded_file($_FILES['SQLDumpFile']['tmp_name'], "$StoragePath/" . basename($_FILES['SQLDumpFile']['name'])))
			{
				$ErrorMSG = "&#149;&nbsp;Move-command for GZipped file failed\n";
				return;
			}
		}
		elseif (stristr(basename($_FILES['SQLDumpFile']['name']), ".sql"))
		{
			$Type = "ascii";

			if (!move_uploaded_file($_FILES['SQLDumpFile']['tmp_name'], "$StoragePath/" . basename($_FILES['SQLDumpFile']['name'])))
			{
				$ErrorMSG = "&#149;&nbsp;Move-command for ASCII file failed\n";
				return;
			}
		}
		else
		{
			$ErrorMSG = "&#149;&nbsp;No compression type defined\n";
			return;
		}

		$FileName = basename($_FILES['SQLDumpFile']['name']);

	}
	else
	{
		$FileName = $_POST['existing_file'];

		if(stristr($FileName, "gz"))
			$Type = "gzip";

		elseif(stristr($FileName, "sql"))
			$Type = "ascii";

		if (!file_exists("$StoragePath/$FileName") || !is_file("$StoragePath/$FileName") || $FileName == "")
		{
			$ErrorMSG .= "&#149;&nbsp;File $StoragePath/$FileName not found\n";
			return;
		}
	}
}

function ProcessSQLFile()
{
	global $_GET, $ErrorMSG, $StoragePath, $ProcessPath, $ThisPage, $Linebuffer;

	$mode = $_GET['type'];

	if ($mode != "ascii" && $mode != "gzip")
	{
		$ErrorMSG .= "&#149;&nbsp;Compression type is not set\n";
		return;
	}

	$FileName = $_GET['file'];

	if (!file_exists("$StoragePath/$FileName") || !is_file("$StoragePath/$FileName") || $FileName == "")
	{
		$ErrorMSG .= "&#149;&nbsp;File $StoragePath/$FileName not found\n";
		return;
	}

	$CountFromHere = 0;
	$PartCount = 1;
	$SplitInParts = $_GET['split'];

	if ($SplitInParts == "Y")
	{
		if ($_GET['splitsize'] != "")
			$SplitSize = ($_GET['splitsize'] * 1000);

		if ($_GET['splitlength'] != "")
			$SplitLength = $_GET['splitlength'];
	}

	clearstatcache();

	$d = dir("$ProcessPath");

	while($entry=$d->read())
	{ 

		if(preg_match("/sqlpart([0-9]{2})\.sql/", $entry))
		{
			unlink ("$ProcessPath/$entry");
		}
	}

	$d->close(); 

	echo "\n...Deleting old existing blocks (if any)\n\n";
	flush();

	if ($mode == "ascii")
	{
		$GetData = fopen ("$StoragePath/$FileName","r");

		$PutData = fopen ("$ProcessPath/sqlpart01.sql","w");

		while(!feof($GetData))
		{
			if ($NextPart == 1)
			{
				fclose ($PutData);
				$NextPart = 0;
				$PartCount++;
				$CountFromHere = 0;
				$FileSize = 0;
				if ($PartCount < 10)
					$PutData = fopen ("$ProcessPath/sqlpart0" . $PartCount . ".sql","w");
				else
					$PutData = fopen ("$ProcessPath/sqlpart" . $PartCount . ".sql","w");
			}

			$line=trim(fgets($GetData, $Linebuffer));

			if (!preg_match("/^#/",$line) && $line != "")
			{
				$newline = $line . "\r\n";
				fwrite ($PutData, $newline);
				$CountFromHere++;
				$FileSize = $FileSize + strlen($newline);
			}

			if ($SplitInParts == "Y")
			{
				if (($CountFromHere > $SplitLength || $FileSize > $SplitSize) && preg_match("/^INSERT INTO/",$line))
					$NextPart = 1;
			}
		}
	}
	elseif ($mode == "gzip")
	{
		$GetData = gzopen ("$StoragePath/$FileName","r");

		$PutData = fopen ("$ProcessPath/sqlpart01.sql","w");

		while(!gzeof($GetData))
		{
			if ($NextPart)
			{
				fclose ($PutData);
				$NextPart = 0;
				$PartCount++;
				$CountFromHere = 0;
				$FileSize = 0;
				if ($PartCount < 10)
					$PutData = fopen ("$ProcessPath/sqlpart0" . $PartCount . ".sql","w");
				else
					$PutData = fopen ("$ProcessPath/sqlpart" . $PartCount . ".sql","w");
			}

			$line=trim(gzgets($GetData, $Linebuffer));

			if (!preg_match("/^#/",$line) && $line != "")
			{
				$newline = $line . "\r\n";
				fwrite ($PutData, $newline);
				$CountFromHere++;
				$FileSize = $FileSize + strlen($newline);
			}

			if ($SplitInParts == "Y")
			{
				if (($CountFromHere > $SplitLength || $FileSize > $SplitSize) && preg_match("/^INSERT INTO/",$line))
					$NextPart = 1;
			}
		}
	}

	if ($SplitInParts == "Y")
		echo "...SQL-file succesfully processed and splitted into $PartCount pieces\n";
	else
		echo "...SQL-file succesfully processed\n";

echo <<<ready_to_restore

---------------------------------------------------------------------------------

<A HREF="$ThisPage?restore=true&sqlparts=$PartCount&part=1">Click here to start RESTORING the SQL-data</A>.

ready_to_restore;

	@fclose ($PutData);
	if ($mode == "ascii")
		fclose ($GetData);
	else
		gzclose ($GetData);
}

function RestoreSQLFile()
{
	global $_GET, $DbCon, $Dbusr, $Dbpass, $Db, $Dblink, $ProcessPath, $ErrorMSG, $UseTimeOverride, $Linebuffer;

	if (!isset($_GET['sqlparts']))
	{
		$ErrorMSG = "Illegal usage of this utility...";
		return;
	}

	$PartsToRestore = $_GET['sqlparts'];
	$CurrentPart = $_GET['part'];

	ConnectDB();
	if ($ErrorMSG != "")
	{
		$ErrorMSG = "\n" . $ErrorMSG;
		return;
	}

	while (1)
	{
		if ($CurrentPart <= $PartsToRestore)
		{
			if ($CurrentPart < 10)
				$RestoreFile = "sqlpart0" . $CurrentPart . ".sql";
			else
				$RestoreFile = "sqlpart" . $CurrentPart . ".sql";

			echo "\n...Restoring file $RestoreFile";
			flush();

			$query = "";

			if (!$GetData = fopen ("$ProcessPath/$RestoreFile","r"))
			{
				$ErrorMSG = "Could not open file $RestoreFile (missing?)";
				return;
			}

			while(!feof($GetData))
			{
				$LineNumber++;
				$line = trim(fgets($GetData, $Linebuffer));

				if (!preg_match("/;$/",$line))
				{
					$query .= $line;
					$IsExecutable = 0;
				}
				else
				{
					$query .= $line;
					$IsExecutable = 1;
				}
				if ($IsExecutable == 1)
				{
					if (!mysql_query($query, $Dblink))
					{
						$ErrorMSG = mysql_error() . "<P>Failed on file $RestoreFile on line $LineNumber<BR>Query: $query";
						return;
					}
					$IsExecutable == 0;
					$query = "";
				}
			}

			echo " -- RESTORED\n";

			$CurrentPart++;

			if ($UseTimeOverride == "Y")
			{
				echo "</PRE>\n<script language=\"javascript\">location.href=\"$ThisPage?restore=true&sqlparts=$PartsToRestore&part=$CurrentPart\";</script>\n</BODY>\n</HTML>";
				break;
			}
		}
		else
		{
			break;
		}

	}
	echo <<<restored

The database was restored succesfully.

---------------------------------------------------------------------------------

<B>END OF PROCESS....</B>

restored;

}

function ConnectDB()
{
	global $DbCon, $Dbusr, $Dbpass, $Db, $Dblink, $ErrorMSG;

	if (!($Dblink = mysql_connect($DbCon, $Dbusr, $Dbpass)))
	{
		$ErrorMSG = "Could not open a MySQL connection";
		return;
	}
			
	if (!mysql_select_db($Db, $Dblink))
	{
		$ErrorMSG = "Could not connect to database $Db";
		return;
	}

}
