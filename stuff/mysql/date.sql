-- DATE
SELECT DATE_FORMAT('2009-01-16 00:00:01', '%Y-%m-%d');
-- TIME
SELECT DATE_FORMAT('2009-01-16 00:00:01', '%H:%i:%s');
-- DAYS
SELECT DATEDIFF('2009-02-16', '2009-02-16 00:00:01');
-- SECONDS
SELECT TIMEDIFF(DATE_FORMAT('2009-02-16', '%Y-%m-%d %H:%i:%s'), '2009-02-15 23:59:01');
-- SAME DAY(2)
SELECT '2009-02-16' = DATE_FORMAT('2009-02-16 00:00:00', '%Y-%m-%d');
-- CURRENT
SELECT NOW();
